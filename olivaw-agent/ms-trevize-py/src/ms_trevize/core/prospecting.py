"""Fronteiras da coleta e da persistência, implementadas pelos adaptadores."""
from typing import Protocol
from ms_trevize.domain.candidate import Candidate


class Collector(Protocol):
  def collect(self, known: set[str]) -> list[Candidate]: ...


class LeadStore(Protocol):
  def preflight(self) -> None: ...
  def publish(self, candidate: Candidate, qualification: dict) -> str: ...


class BatchState(Protocol):
  settings: dict
  def prepare(self) -> None: ...
  def seen(self) -> dict: ...
  def remember(self, seen: dict, key: str) -> None: ...
  def stopping(self) -> bool: ...
  def save(self, report: dict) -> None: ...
