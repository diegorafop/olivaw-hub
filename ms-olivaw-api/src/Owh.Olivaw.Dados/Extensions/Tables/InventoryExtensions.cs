using Microsoft.EntityFrameworkCore;
using Owh.Olivaw.Domain;
namespace Owh.Olivaw.Dados.Extensions.Tables;

internal static class InventoryExtensions
{
    internal static void SetupInventory(this ModelBuilder builder)
    {
        var resource = builder.Entity<InventoryResource>();
        resource.ToTable("inventoryresource"); resource.HasKey(item => item.Id);
        resource.HasIndex(item => item.ExternalId).IsUnique();
        resource.HasIndex(item => item.TechnicalId).IsUnique();
        resource.HasIndex(item => item.ProviderIdentityKey).IsUnique().HasFilter("provideridentitykey IS NOT NULL");
        resource.Property(item => item.TechnicalId).HasMaxLength(80).IsRequired();
        resource.Property(item => item.ProviderIdentityKey).HasMaxLength(64);
        resource.Property(item => item.Revision).IsConcurrencyToken();
        var change = builder.Entity<InventoryResourceChange>();
        change.ToTable("inventoryresourcechange"); change.HasKey(item => item.Id);
        change.HasIndex(item => new { item.InventoryResourceId, item.Revision }).IsUnique();
        change.HasOne(item => item.InventoryResource).WithMany(item => item.Changes).HasForeignKey(item => item.InventoryResourceId).OnDelete(DeleteBehavior.Restrict);
        change.Property(item => item.ActorName).HasMaxLength(120).IsRequired();
        resource.Property(item => item.Name).HasMaxLength(120).IsRequired();
        change.Property(item => item.Name).HasMaxLength(120).IsRequired();
        resource.Property(item => item.Type).HasMaxLength(30).IsRequired();
        change.Property(item => item.Type).HasMaxLength(30).IsRequired();
        resource.Property(item => item.Purpose).HasMaxLength(1000).IsRequired();
        change.Property(item => item.Purpose).HasMaxLength(1000).IsRequired();
        resource.Property(item => item.Provider).HasMaxLength(80).IsRequired();
        change.Property(item => item.Provider).HasMaxLength(80).IsRequired();
        resource.Property(item => item.AccountReference).HasMaxLength(120).IsRequired();
        change.Property(item => item.AccountReference).HasMaxLength(120).IsRequired();
        resource.Property(item => item.Region).HasMaxLength(80).IsRequired();
        change.Property(item => item.Region).HasMaxLength(80).IsRequired();
        resource.Property(item => item.ProviderResourceId).HasMaxLength(180).IsRequired();
        change.Property(item => item.ProviderResourceId).HasMaxLength(180).IsRequired();
        resource.Property(item => item.Owner).HasMaxLength(120).IsRequired();
        change.Property(item => item.Owner).HasMaxLength(120).IsRequired();
        resource.Property(item => item.Payer).HasMaxLength(120).IsRequired();
        change.Property(item => item.Payer).HasMaxLength(120).IsRequired();
        resource.Property(item => item.Operator).HasMaxLength(120).IsRequired();
        change.Property(item => item.Operator).HasMaxLength(120).IsRequired();
        resource.Property(item => item.Scope).HasMaxLength(20).IsRequired();
        change.Property(item => item.Scope).HasMaxLength(20).IsRequired();
        resource.Property(item => item.Status).HasMaxLength(20).IsRequired();
        change.Property(item => item.Status).HasMaxLength(20).IsRequired();
        resource.Property(item => item.Source).HasMaxLength(500).IsRequired();
        change.Property(item => item.Source).HasMaxLength(500).IsRequired();
        resource.Property(item => item.Monitoring).HasMaxLength(20).IsRequired();
        change.Property(item => item.Monitoring).HasMaxLength(20).IsRequired();
        resource.Property(item => item.ReferenceUrl).HasMaxLength(300).IsRequired();
        change.Property(item => item.ReferenceUrl).HasMaxLength(300).IsRequired();
        resource.Property(item => item.CpuCapacity).HasPrecision(18, 3);
        change.Property(item => item.CpuCapacity).HasPrecision(18, 3);
        resource.Property(item => item.MemoryCapacityGiB).HasPrecision(18, 3);
        change.Property(item => item.MemoryCapacityGiB).HasPrecision(18, 3);
        resource.Property(item => item.StorageCapacityGiB).HasPrecision(18, 3);
        change.Property(item => item.StorageCapacityGiB).HasPrecision(18, 3);
        var gate = builder.Entity<InventoryRevision>();
        gate.ToTable("inventoryrevision"); gate.HasKey(item => item.Id);
        gate.Property(item => item.Key).HasMaxLength(20).IsRequired(); gate.HasIndex(item => item.Key).IsUnique();
        gate.Property(item => item.Revision).IsConcurrencyToken();
        var deployment = builder.Entity<ServiceDeployment>();
        deployment.ToTable("servicedeployment"); deployment.HasKey(item => item.Id);
        deployment.HasIndex(item => item.ExternalId).IsUnique();
        deployment.HasIndex(item => new { item.ManagedServiceId, item.Environment }).IsUnique().HasFilter("endedat IS NULL");
        deployment.Property(item => item.Name).HasMaxLength(120).IsRequired();
        deployment.Property(item => item.Environment).HasMaxLength(20).IsRequired();
        deployment.Property(item => item.Location).HasMaxLength(200).IsRequired();
        deployment.Property(item => item.Endpoint).HasMaxLength(300).IsRequired();
        deployment.Property(item => item.Status).HasMaxLength(20).IsRequired();
        deployment.Property(item => item.Revision).IsConcurrencyToken();
        deployment.HasOne(item => item.ManagedService).WithMany().HasForeignKey(item => item.ManagedServiceId).OnDelete(DeleteBehavior.Restrict);
        var deploymentChange = builder.Entity<ServiceDeploymentChange>();
        deploymentChange.ToTable("servicedeploymentchange"); deploymentChange.HasKey(item => item.Id);
        deploymentChange.HasIndex(item => new { item.ServiceDeploymentId, item.Revision }).IsUnique();
        deploymentChange.HasOne(item => item.ServiceDeployment).WithMany(item => item.Changes).HasForeignKey(item => item.ServiceDeploymentId).OnDelete(DeleteBehavior.Restrict);
        deploymentChange.Property(item => item.Name).HasMaxLength(120).IsRequired();
        deploymentChange.Property(item => item.ActorName).HasMaxLength(120).IsRequired();
        deploymentChange.Property(item => item.Location).HasMaxLength(200).IsRequired();
        deploymentChange.Property(item => item.Endpoint).HasMaxLength(300).IsRequired();
        deploymentChange.Property(item => item.Status).HasMaxLength(20).IsRequired();
        var customer = builder.Entity<ResourceCustomer>();
        customer.ToTable("resourcecustomer"); customer.HasKey(item => item.Id);
        customer.HasIndex(item => item.ExternalId).IsUnique();
        customer.Property(item => item.Purpose).HasMaxLength(300).IsRequired();
        customer.Property(item => item.StartedByName).HasMaxLength(120).IsRequired();
        customer.Property(item => item.EndedByName).HasMaxLength(120);
        customer.Property(item => item.Revision).IsConcurrencyToken();
        customer.HasOne(item => item.InventoryResource).WithMany().HasForeignKey(item => item.InventoryResourceId).OnDelete(DeleteBehavior.Restrict);
        customer.HasOne(item => item.Customer).WithMany().HasForeignKey(item => item.CustomerId).OnDelete(DeleteBehavior.Restrict);
        customer.HasIndex(item => new { item.InventoryResourceId, item.CustomerId }).IsUnique().HasFilter("endedat IS NULL");

        var dependency = builder.Entity<ResourceDependency>();
        dependency.ToTable("resourcedependency"); dependency.HasKey(item => item.Id);
        dependency.HasIndex(item => item.ExternalId).IsUnique();
        dependency.Property(item => item.Purpose).HasMaxLength(300).IsRequired();
        dependency.Property(item => item.StartedByName).HasMaxLength(120).IsRequired();
        dependency.Property(item => item.EndedByName).HasMaxLength(120);
        dependency.Property(item => item.Revision).IsConcurrencyToken();
        dependency.HasOne(item => item.SourceResource).WithMany().HasForeignKey(item => item.SourceResourceId).OnDelete(DeleteBehavior.Restrict);
        dependency.HasOne(item => item.TargetResource).WithMany().HasForeignKey(item => item.TargetResourceId).OnDelete(DeleteBehavior.Restrict);
        dependency.HasIndex(item => new { item.SourceResourceId, item.TargetResourceId, item.Kind }).IsUnique().HasFilter("endedat IS NULL");
        dependency.Property(item => item.Kind).HasMaxLength(20).IsRequired();

        var use = builder.Entity<DeploymentResource>();
        use.ToTable("deploymentresource"); use.HasKey(item => item.Id);
        use.HasIndex(item => item.ExternalId).IsUnique();
        use.Property(item => item.Purpose).HasMaxLength(300).IsRequired();
        use.Property(item => item.StartedByName).HasMaxLength(120).IsRequired();
        use.Property(item => item.EndedByName).HasMaxLength(120);
        use.Property(item => item.Revision).IsConcurrencyToken();
        use.HasOne(item => item.InventoryResource).WithMany().HasForeignKey(item => item.InventoryResourceId).OnDelete(DeleteBehavior.Restrict);
        use.HasOne(item => item.ServiceDeployment).WithMany().HasForeignKey(item => item.ServiceDeploymentId).OnDelete(DeleteBehavior.Restrict);
        use.HasIndex(item => new { item.InventoryResourceId, item.ServiceDeploymentId }).IsUnique().HasFilter("endedat IS NULL");
        use.Property(item => item.ReservedCpu).HasPrecision(18, 3);
        use.Property(item => item.ReservedMemoryGiB).HasPrecision(18, 3);
        use.Property(item => item.ReservedStorageGiB).HasPrecision(18, 3);

    }
}
